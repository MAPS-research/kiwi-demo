import { render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it, vi } from 'vitest';
import App from './App';
import { DemoProvider, initialState, STORAGE_KEY } from './state';
function setup() { render(<DemoProvider><App /></DemoProvider>); return userEvent.setup(); }

describe('connected demo journeys', () => {
  it('supports keyboard card selection and moves focus between lesson pages and assistant', async () => {
    const user = setup();
    await user.click(screen.getByRole('button', { name: /Explore as a student/ }));
    await user.click(within(screen.getByRole('navigation', { name: 'Lesson pages' })).getByRole('button', { name: 'Next' }));
    expect(screen.getByRole('heading', { name: 'Which cards help?' })).toHaveFocus();
    await user.click(screen.getByRole('link', { name: /Draw Lab/ }));
    const heart = screen.getByRole('button', { name: '3 of hearts' });
    heart.focus();
    await user.keyboard(' ');
    expect(heart).toHaveAttribute('aria-pressed', 'true');
    await user.click(screen.getByRole('button', { name: 'Ask Kiwi' }));
    expect(screen.getByRole('textbox', { name: 'Sample question' })).toHaveFocus();
    await user.keyboard('{Escape}');
    await waitFor(() => expect(screen.getByRole('button', { name: 'Ask Kiwi' })).toHaveFocus());
  });
  it('lets a teacher add practice and save instructions that a student experiences', async () => {
    const user = setup();
    await user.click(screen.getByRole('button', { name: /Explore as a teacher/ }));
    await user.click(await screen.findByRole('button', { name: /Add sample material/ }));
    await user.click(screen.getByRole('link', { name: 'Edit Class' }));
    await user.click(await screen.findByRole('radio', { name: /Ask a guiding question first/ }));
    await user.click(screen.getByRole('button', { name: 'Save changes' }));
    await user.click(screen.getByRole('button', { name: 'Student' }));
    await user.click(screen.getByRole('button', { name: 'Recitation' }));
    await user.click(screen.getByRole('button', { name: /Count the cards Practice sheet/ }));
    expect(screen.getByRole('heading', { name: 'Count the cards.' })).toBeVisible();
    await user.click(screen.getByRole('button', { name: 'Ask for a hint' }));
    await user.click(screen.getByRole('button', { name: 'Why are there nine helpful cards?' }));
    await user.click(screen.getByRole('button', { name: 'Send question' }));
    await screen.findByText('Kiwi finished the sample answer.');
    expect(screen.getByText(/Start with what you can see/)).toBeVisible();
    expect(screen.queryByText(/your chance is 9\/47/)).not.toBeInTheDocument();
  });
  it('updates app availability and safely handles a disabled app direct link', async () => {
    const user = setup();
    await user.click(screen.getByRole('button', { name: /Explore as a teacher/ }));
    await user.click(await screen.findByRole('link', { name: 'Class Apps' }));
    await user.click(await screen.findByRole('button', { name: 'Disable Draw Lab' }));
    await user.click(screen.getByRole('button', { name: 'Student' }));
    expect(screen.queryByRole('link', { name: /Draw Lab/ })).not.toBeInTheDocument();
    window.location.hash = '/student/draw-lab';
    window.dispatchEvent(new HashChangeEvent('hashchange'));
    await waitFor(() => expect(window.location.hash).toBe('#/student/materials'));
    expect(screen.getByText(/Draw Lab is disabled for this class/)).toBeVisible();
  });
  it('counts selected hearts, draws unique cards, and resets the lab', async () => {
    const user = setup();
    await user.click(screen.getByRole('button', { name: /Explore as a student/ }));
    await user.click(screen.getByRole('link', { name: /Draw Lab/ }));
    for (const rank of ['3', '4', '5', '6', '8', '9', '10', 'Jack', 'Queen']) await user.click(screen.getByRole('button', { name: `${rank} of hearts` }));
    await user.click(screen.getByRole('button', { name: 'Check my selection' }));
    expect(screen.getByText('Exactly. 9 hearts out of 47 unseen cards.')).toBeVisible();
    const random = vi.spyOn(Math, 'random').mockReturnValue(0.5);
    await user.click(screen.getByRole('button', { name: 'Reveal the turn' }));
    await user.click(screen.getByRole('button', { name: 'Reveal the river' }));
    expect(screen.getByRole('button', { name: 'Both cards revealed' })).toBeDisabled();
    const saved = JSON.parse(sessionStorage.getItem(STORAGE_KEY)!);
    expect(new Set(saved.drawn).size).toBe(2);
    await user.click(screen.getByRole('button', { name: 'Reset hand' }));
    expect(screen.getByRole('button', { name: 'Reveal the turn' })).toBeEnabled();
    expect(screen.getByText('19.1%')).toBeVisible();
    random.mockRestore();
  });
  it('applies app picker changes only after saving them', async () => {
    const user = setup();
    await user.click(screen.getByRole('button', { name: /Explore as a teacher/ }));
    await user.click(await screen.findByRole('link', { name: 'Class Apps' }));
    await user.click(await screen.findByRole('button', { name: 'Disable Draw Lab' }));
    await user.click(screen.getByRole('button', { name: 'Enable Apps' }));
    await user.click(screen.getByRole('checkbox', { name: 'Enable Draw Lab' }));
    await user.click(screen.getByRole('button', { name: 'Cancel' }));
    expect(screen.getByRole('heading', { name: 'No Apps Enabled' })).toBeVisible();
    await user.click(screen.getByRole('button', { name: 'Enable Apps' }));
    expect(screen.getByRole('checkbox', { name: 'Enable Draw Lab' })).not.toBeChecked();
    await user.click(screen.getByRole('checkbox', { name: 'Enable Draw Lab' }));
    await user.click(screen.getByRole('button', { name: 'Apply changes' }));
    await user.click(screen.getByRole('button', { name: 'Student' }));
    expect(screen.getByRole('link', { name: 'Draw Lab' })).toBeVisible();
  });
  it('keeps chat responses when switching between modal, side panel, and fullscreen', async () => {
    const user = setup();
    await user.click(screen.getByRole('button', { name: /Explore as a student/ }));
    await user.click(screen.getByRole('button', { name: 'Ask Kiwi' }));
    expect(screen.getByRole('dialog', { name: 'Kiwi assistant' })).toBeVisible();
    await user.click(screen.getByRole('button', { name: 'Why are there nine helpful cards?' }));
    await user.click(screen.getByRole('button', { name: 'Send question' }));
    await screen.findByText('Kiwi finished the sample answer.');
    await user.click(screen.getByRole('button', { name: 'Side panel view' }));
    expect(screen.queryByRole('dialog', { name: 'Kiwi assistant' })).not.toBeInTheDocument();
    expect(within(screen.getByRole('complementary', { name: 'Kiwi assistant' })).getByText(/A deck has 13 hearts/)).toBeVisible();
    await user.click(screen.getByRole('button', { name: 'Fullscreen chat' }));
    expect(within(screen.getByRole('dialog', { name: 'Kiwi assistant' })).getByText(/A deck has 13 hearts/)).toBeVisible();
    await user.keyboard('{Escape}');
    await waitFor(() => expect(screen.getByRole('button', { name: 'Ask Kiwi' })).toHaveFocus());
  });
  it('opens cited lesson pages from scripted replies', async () => {
    const user = setup();
    await user.click(screen.getByRole('button', { name: /Explore as a student/ }));
    await user.click(screen.getAllByRole('button', { name: 'Ask Kiwi' })[0]);
    await user.click(screen.getByRole('button', { name: 'Why isn’t two draws exactly twice the chance?' }));
    await user.click(screen.getByRole('button', { name: 'Send question' }));
    await screen.findByText('Kiwi finished the sample answer.');
    await user.click(screen.getByRole('button', { name: /One chance or two\? · p. 3/ }));
    expect(screen.getByRole('heading', { name: 'One chance or two?' })).toBeVisible();
    expect(screen.queryByRole('complementary', { name: 'Kiwi assistant' })).not.toBeInTheDocument();
  });
  it('preserves student tour progress across a role switch and finishes both tours', async () => {
    const user = setup();
    await user.click(screen.getByRole('button', { name: /Explore as a student/ }));
    await user.click(screen.getByRole('button', { name: 'Take a tour' }));
    await user.click(within(screen.getByRole('region', { name: 'student tour' })).getByRole('button', { name: 'Next' }));
    expect(screen.getByRole('heading', { name: 'A little help, in context' })).toBeVisible();
    await user.click(screen.getByRole('button', { name: 'Teacher' }));
    await user.click(await screen.findByRole('button', { name: 'Take a tour' }));
    for (let i = 0; i < 3; i++) await user.click(within(screen.getByRole('region', { name: 'teacher tour' })).getByRole('button', { name: 'Next' }));
    await user.click(within(screen.getByRole('region', { name: 'teacher tour' })).getByRole('button', { name: 'Finish' }));
    await user.click(screen.getByRole('button', { name: 'Explore as a student' }));
    await user.click(screen.getByRole('button', { name: 'Continue tour' }));
    expect(screen.getByRole('heading', { name: 'A little help, in context' })).toBeVisible();
    for (let i = 0; i < 2; i++) await user.click(within(screen.getByRole('region', { name: 'student tour' })).getByRole('button', { name: 'Next' }));
    await user.click(within(screen.getByRole('region', { name: 'student tour' })).getByRole('button', { name: 'Finish' }));
    expect(screen.getByRole('button', { name: 'Explore as a teacher' })).toBeVisible();
  });
  it('filters synthetic analytics and opens a related question', async () => {
    const user = setup();
    await user.click(screen.getByRole('button', { name: /Explore as a teacher/ }));
    await user.click(await screen.findByRole('link', { name: 'Class Analytics' }));
    await user.selectOptions(await screen.findByRole('combobox', { name: 'Material' }), 'practice');
    await user.click(screen.getByRole('button', { name: /Unseen cards/ }));
    expect(screen.getByText('Should I subtract the cards the other players have?')).toBeVisible();
    expect(screen.queryByText('Why do we start with 47 cards instead of 52?')).not.toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: /Should I subtract/ }));
    expect(screen.getByRole('dialog', { name: 'A closer look at the question' })).toBeVisible();
    await user.click(screen.getByRole('button', { name: 'Open related lesson' }));
    expect(screen.getByRole('heading', { name: 'Meet your hand' })).toBeVisible();
  });
  it('restores a saved deep link and resets the full demo', async () => {
    sessionStorage.setItem(STORAGE_KEY, JSON.stringify({ ...initialState(), practiceAdded: true, preset: 'guiding' }));
    window.location.hash = '/student/draw-lab';
    const user = setup();
    expect(screen.getByRole('heading', { name: /Draw Lab/ })).toBeVisible();
    await user.click(screen.getByRole('button', { name: 'Reset demo' }));
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Reset demo' }));
    expect(screen.getByRole('heading', { name: /See learning/ })).toBeVisible();
    expect(JSON.parse(sessionStorage.getItem(STORAGE_KEY)!)).toEqual(initialState());
  });
});
